fn main() {
    // Tauri's context macro expects a default PNG icon at this path even
    // when bundle.icon is empty. Keep a tiny valid fallback so clean clones
    // compile without requiring generated platform icon assets.
    const FALLBACK_ICON: &[u8] = &[
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
        0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
        0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4,
        0x89, 0x00, 0x00, 0x00, 0x0b, 0x49, 0x44, 0x41,
        0x54, 0x78, 0x9c, 0x63, 0x60, 0x00, 0x02, 0x00,
        0x00, 0x05, 0x00, 0x01, 0xa5, 0xf6, 0x45, 0x40,
        0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44,
        0xae, 0x42, 0x60, 0x82,
    ];

    let icon_dir = std::path::Path::new("icons");
    std::fs::create_dir_all(icon_dir).expect("create Tauri icons directory");
    let icon_path = icon_dir.join("icon.png");
    if !icon_path.exists() {
        std::fs::write(&icon_path, FALLBACK_ICON).expect("write fallback Tauri icon");
    }

    tauri_build::build()
}
